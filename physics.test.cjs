const assert = require('node:assert/strict');
require('./physics.js');
const step = LumiPhysics.step;
const platform = {x:100,y:200,w:200,h:22};
let b = {x:150,y:80,w:40,h:62,vx:0,vy:900};
for(let i=0;i<30;i++) step(b,[platform],1/60);
assert.equal(b.y,138); assert.equal(b.onGround,true);
b={x:50,y:180,w:40,h:62,vx:300,vy:0};
step(b,[platform],.05); assert.equal(b.x,60); assert.equal(b.vx,0);
b={x:150,y:225,w:40,h:62,vx:0,vy:-760};
step(b,[platform],.02); assert.ok(b.y>=222); assert.ok(b.vy>=0);
b={x:3300,y:450,w:40,h:62,vx:0,vy:400};
const bridge={x:3100,y:558,w:760,h:27};
for(let i=0;i<60;i++) step(b,[bridge],1/60);
assert.equal(b.y,496);
b={x:3300,y:610,w:40,h:62,vx:0,vy:0};
for(let i=0;i<60;i++) step(b,[],1/60);
assert.ok(b.y>820);
console.log('5 collision regressions passed: landing, wall, ceiling, bridge, water fall');
